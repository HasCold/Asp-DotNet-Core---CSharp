// External Data Type   And   Internal Data Type

// - Internal Data Type or Abstract Data Type

// Two types of Data Structure or Memory 
// 1. Stack Memory   2. Heap Memory

// In Stack, usually primitive data types will be stored
// Unlike Struct and Enums (both are non-primitive) becuase they are value data-types, they will also be stored in Stack memory. 

// In Heap, usually non-primitive or reference data types will be stored, 80% usually non-primitive type stored here.
// E.g. :- String s = new String();  -->> Go into the Heap memory